export function restoreTableCountQuery(table) {
  if (typeof table !== "string" || !/^[a-z][a-z0-9_]{0,62}$/u.test(table)) {
    throw new Error("Database returned an unsafe table name");
  }
  return Object.freeze([`select count(*) from public."${table}"`]);
}
